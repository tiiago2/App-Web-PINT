CREATE TABLE IF NOT EXISTS mobile_sync_changes (
  change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity VARCHAR(64) NOT NULL,
  record_id VARCHAR(255) NOT NULL,
  id_utilizador INTEGER NULL,
  operation VARCHAR(10) NOT NULL,
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  metadata_json JSONB NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_mobile_sync_changes_operation
    CHECK (operation IN ('insert', 'update', 'delete'))
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'ck_mobile_sync_changes_operation'
      AND conrelid = 'mobile_sync_changes'::regclass
  ) THEN
    ALTER TABLE mobile_sync_changes
      ADD CONSTRAINT ck_mobile_sync_changes_operation
      CHECK (operation IN ('insert', 'update', 'delete'));
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_mobile_sync_changes_cursor
  ON mobile_sync_changes (changed_at, change_id);

CREATE INDEX IF NOT EXISTS idx_mobile_sync_changes_user_cursor
  ON mobile_sync_changes (id_utilizador, changed_at, change_id);

CREATE INDEX IF NOT EXISTS idx_mobile_sync_changes_entity_record
  ON mobile_sync_changes (entity, record_id);

CREATE OR REPLACE FUNCTION mobile_sync_log_generic()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  old_data JSONB;
  entity_name TEXT := TG_ARGV[0];
  record_columns TEXT[] := string_to_array(TG_ARGV[1], ',');
  user_column TEXT := COALESCE(TG_ARGV[2], '');
  soft_delete_column TEXT := COALESCE(TG_ARGV[3], '');
  metadata_columns TEXT[] := string_to_array(COALESCE(TG_ARGV[4], ''), ',');
  record_column TEXT;
  metadata_column TEXT;
  record_parts TEXT[] := ARRAY[]::TEXT[];
  record_value TEXT;
  user_id INTEGER := NULL;
  event_operation TEXT;
  metadata JSONB := '{}'::JSONB;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  old_data := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) ELSE '{}'::JSONB END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  FOREACH record_column IN ARRAY record_columns LOOP
    record_value := row_data ->> btrim(record_column);
    IF record_value IS NULL THEN
      IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
      RETURN NEW;
    END IF;
    record_parts := array_append(record_parts, record_value);
  END LOOP;

  IF user_column <> '' THEN
    user_id := NULLIF(row_data ->> user_column, '')::INTEGER;
  END IF;

  event_operation := lower(TG_OP);
  IF TG_OP = 'DELETE' OR (
    soft_delete_column <> ''
    AND COALESCE((row_data ->> soft_delete_column)::BOOLEAN, FALSE)
    AND NOT COALESCE((old_data ->> soft_delete_column)::BOOLEAN, FALSE)
  ) THEN
    event_operation := 'delete';
  END IF;

  FOREACH metadata_column IN ARRAY metadata_columns LOOP
    metadata_column := btrim(metadata_column);
    IF metadata_column <> '' THEN
      metadata := metadata || jsonb_build_object(
        metadata_column,
        row_data -> metadata_column
      );
    END IF;
  END LOOP;

  INSERT INTO mobile_sync_changes (
    entity,
    record_id,
    id_utilizador,
    operation,
    metadata_json
  ) VALUES (
    entity_name,
    array_to_string(record_parts, ':'),
    user_id,
    event_operation,
    NULLIF(metadata, '{}'::JSONB)
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile em %.%', TG_TABLE_NAME, TG_OP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_submission_related()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  old_data JSONB;
  entity_name TEXT := TG_ARGV[0];
  record_columns TEXT[] := string_to_array(TG_ARGV[1], ',');
  soft_delete_column TEXT := COALESCE(TG_ARGV[2], '');
  metadata_columns TEXT[] := string_to_array(COALESCE(TG_ARGV[3], ''), ',');
  column_name TEXT;
  record_parts TEXT[] := ARRAY[]::TEXT[];
  metadata JSONB := '{}'::JSONB;
  user_id INTEGER;
  event_operation TEXT;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  old_data := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) ELSE '{}'::JSONB END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  SELECT id_utilizador
  INTO user_id
  FROM submissoes
  WHERE id_submissao = (row_data ->> 'id_submissao')::INTEGER;

  IF user_id IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  FOREACH column_name IN ARRAY record_columns LOOP
    record_parts := array_append(record_parts, row_data ->> btrim(column_name));
  END LOOP;

  event_operation := lower(TG_OP);
  IF TG_OP = 'DELETE' OR (
    soft_delete_column <> ''
    AND COALESCE((row_data ->> soft_delete_column)::BOOLEAN, FALSE)
    AND NOT COALESCE((old_data ->> soft_delete_column)::BOOLEAN, FALSE)
  ) THEN
    event_operation := 'delete';
  END IF;

  FOREACH column_name IN ARRAY metadata_columns LOOP
    column_name := btrim(column_name);
    IF column_name <> '' THEN
      metadata := metadata || jsonb_build_object(column_name, row_data -> column_name);
    END IF;
  END LOOP;

  INSERT INTO mobile_sync_changes (
    entity, record_id, id_utilizador, operation, metadata_json
  ) VALUES (
    entity_name,
    array_to_string(record_parts, ':'),
    user_id,
    event_operation,
    NULLIF(metadata, '{}'::JSONB)
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile relacionada com submissão em %.%', TG_TABLE_NAME, TG_OP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_signature_badge()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  user_id INTEGER;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  SELECT id_proprietario
  INTO user_id
  FROM assinatura
  WHERE id_assinatura = (row_data ->> 'id_assinatura')::INTEGER;

  IF user_id IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  INSERT INTO mobile_sync_changes (
    entity, record_id, id_utilizador, operation, metadata_json
  ) VALUES (
    'signature_badges',
    (row_data ->> 'id_assinatura') || ':' || (row_data ->> 'id_badge'),
    user_id,
    lower(TG_OP),
    jsonb_build_object(
      'id_assinatura', row_data -> 'id_assinatura',
      'id_badge', row_data -> 'id_badge'
    )
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile de badge da assinatura.';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_notification()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  receiver RECORD;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  FOR receiver IN
    SELECT id_utilizador
    FROM recetor
    WHERE id_notificacao = (row_data ->> 'id_notificacao')::INTEGER
  LOOP
    INSERT INTO mobile_sync_changes (
      entity, record_id, id_utilizador, operation, metadata_json
    ) VALUES (
      'notifications',
      row_data ->> 'id_notificacao',
      receiver.id_utilizador,
      lower(TG_OP),
      jsonb_build_object('id_notificacao', row_data -> 'id_notificacao')
    );
  END LOOP;

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile de notificação.';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

