  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_signature_badge()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  user_id INTEGER;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  SELECT id_proprietario
  INTO user_id
  FROM assinatura
  WHERE id_assinatura = (row_data ->> 'id_assinatura')::INTEGER;

  IF user_id IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  INSERT INTO mobile_sync_changes (
    entity, record_id, id_utilizador, operation, metadata_json
  ) VALUES (
    'signature_badges',
    (row_data ->> 'id_assinatura') || ':' || (row_data ->> 'id_badge'),
    user_id,
    lower(TG_OP),
    jsonb_build_object(
      'id_assinatura', row_data -> 'id_assinatura',
      'id_badge', row_data -> 'id_badge'
    )
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile de badge da assinatura.';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_notification()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  receiver RECORD;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  FOR receiver IN
    SELECT id_utilizador
    FROM recetor
    WHERE id_notificacao = (row_data ->> 'id_notificacao')::INTEGER
  LOOP
    INSERT INTO mobile_sync_changes (
      entity, record_id, id_utilizador, operation, metadata_json
    ) VALUES (
      'notifications',
      row_data ->> 'id_notificacao',
      receiver.id_utilizador,
      lower(TG_OP),
      jsonb_build_object('id_notificacao', row_data -> 'id_notificacao')
    );
  END LOOP;

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile de notificação.';
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

