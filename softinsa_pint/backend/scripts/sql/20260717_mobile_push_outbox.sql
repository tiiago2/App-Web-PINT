BEGIN;

CREATE TABLE IF NOT EXISTS mobile_push_outbox (
  id_mobile_push BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_utilizador INTEGER NOT NULL,
  event_type VARCHAR(32) NOT NULL DEFAULT 'data_changed',
  entity VARCHAR(64) NOT NULL,
  payload_json JSONB NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_error_code VARCHAR(128) NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at TIMESTAMP WITH TIME ZONE NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_mobile_push_outbox_user
    FOREIGN KEY (id_utilizador)
    REFERENCES utilizador (id_utilizador)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  CONSTRAINT ck_mobile_push_outbox_event_type
    CHECK (event_type IN ('data_changed')),
  CONSTRAINT ck_mobile_push_outbox_status
    CHECK (status IN (
      'pending',
      'processing',
      'sent',
      'retryable_error',
      'permanent_error'
    )),
  CONSTRAINT ck_mobile_push_outbox_attempts
    CHECK (attempts >= 0),
  CONSTRAINT ck_mobile_push_outbox_payload_object
    CHECK (jsonb_typeof(payload_json) = 'object')
);

-- Garante as constraints mesmo que o sequelize.sync tenha criado a tabela
-- antes da execucao manual deste script.
ALTER TABLE mobile_push_outbox
  DROP CONSTRAINT IF EXISTS fk_mobile_push_outbox_user,
  DROP CONSTRAINT IF EXISTS ck_mobile_push_outbox_event_type,
  DROP CONSTRAINT IF EXISTS ck_mobile_push_outbox_status,
  DROP CONSTRAINT IF EXISTS ck_mobile_push_outbox_attempts,
  DROP CONSTRAINT IF EXISTS ck_mobile_push_outbox_payload_object;

ALTER TABLE mobile_push_outbox
  ADD CONSTRAINT fk_mobile_push_outbox_user
    FOREIGN KEY (id_utilizador)
    REFERENCES utilizador (id_utilizador)
    ON UPDATE CASCADE
    ON DELETE CASCADE,
  ADD CONSTRAINT ck_mobile_push_outbox_event_type
    CHECK (event_type IN ('data_changed')),
  ADD CONSTRAINT ck_mobile_push_outbox_status
    CHECK (status IN (
      'pending',
      'processing',
      'sent',
      'retryable_error',
      'permanent_error'
    )),
  ADD CONSTRAINT ck_mobile_push_outbox_attempts
    CHECK (attempts >= 0),
  ADD CONSTRAINT ck_mobile_push_outbox_payload_object
    CHECK (jsonb_typeof(payload_json) = 'object');

CREATE INDEX IF NOT EXISTS idx_mobile_push_outbox_due
  ON mobile_push_outbox (status, next_attempt_at);

CREATE INDEX IF NOT EXISTS idx_mobile_push_outbox_user
  ON mobile_push_outbox (id_utilizador);

CREATE UNIQUE INDEX IF NOT EXISTS uq_mobile_push_outbox_user_pending_event
  ON mobile_push_outbox (id_utilizador, event_type)
  WHERE status IN ('pending', 'retryable_error');

CREATE OR REPLACE FUNCTION mobile_push_enqueue_data_changed()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  existing_entity VARCHAR(64);
  coalesced_entity VARCHAR(64);
BEGIN
  -- Eventos globais ficam fora deste fan-out para evitar criar milhares de
  -- linhas durante a transacao que alterou o catalogo.
  IF NEW.id_utilizador IS NULL OR NEW.entity NOT IN (
    'profile',
    'badge_records',
    'submissions',
    'submission_documents',
    'history',
    'objectives',
    'notifications',
    'notification_receivers',
    'signature',
    'signature_badges'
  ) THEN
    RETURN NEW;
  END IF;

  -- Serializa apenas a coalescencia do mesmo utilizador nesta transacao.
  PERFORM pg_advisory_xact_lock(NEW.id_utilizador::BIGINT);

  SELECT entity
  INTO existing_entity
  FROM mobile_push_outbox
  WHERE id_utilizador = NEW.id_utilizador
    AND event_type = 'data_changed'
    AND status IN ('pending', 'retryable_error')
  ORDER BY id_mobile_push
  LIMIT 1
  FOR UPDATE;

  IF FOUND THEN
    coalesced_entity := CASE
      WHEN existing_entity = NEW.entity THEN NEW.entity
      ELSE 'multiple'
    END;

    UPDATE mobile_push_outbox
    SET entity = coalesced_entity,
        payload_json = jsonb_build_object(
          'type', 'data_changed'::TEXT,
          'entity', coalesced_entity::TEXT,
          'version', NEW.change_id::TEXT
        ),
        status = 'pending',
        attempts = 0,
        next_attempt_at = CURRENT_TIMESTAMP,
        last_error_code = NULL,
        sent_at = NULL,
        updated_at = CURRENT_TIMESTAMP
    WHERE id_utilizador = NEW.id_utilizador
      AND event_type = 'data_changed'
      AND status IN ('pending', 'retryable_error');
  ELSE
    INSERT INTO mobile_push_outbox (
      id_utilizador,
      event_type,
      entity,
      payload_json,
      status,
      attempts,
      next_attempt_at,
      created_at,
      updated_at
    ) VALUES (
      NEW.id_utilizador,
      'data_changed',
      NEW.entity,
      jsonb_build_object(
        'type', 'data_changed'::TEXT,
        'entity', NEW.entity::TEXT,
        'version', NEW.change_id::TEXT
      ),
      'pending',
      0,
      CURRENT_TIMESTAMP,
      CURRENT_TIMESTAMP,
      CURRENT_TIMESTAMP
    );
  END IF;

  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  -- A indisponibilidade da outbox nunca reverte a alteracao de negocio.
  RAISE WARNING 'Nao foi possivel criar aviso mobile data_changed.';
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_mobile_push_from_sync_change ON mobile_sync_changes;
CREATE TRIGGER trg_mobile_push_from_sync_change
AFTER INSERT ON mobile_sync_changes
FOR EACH ROW EXECUTE FUNCTION mobile_push_enqueue_data_changed();

COMMIT;
