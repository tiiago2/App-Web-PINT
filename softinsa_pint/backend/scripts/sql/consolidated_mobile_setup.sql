CREATE OR REPLACE FUNCTION mobile_sync_log_generic()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  old_data JSONB;
  entity_name TEXT := TG_ARGV[0];
  record_columns TEXT[] := string_to_array(TG_ARGV[1], ',');
  user_column TEXT := COALESCE(TG_ARGV[2], '');
  soft_delete_column TEXT := COALESCE(TG_ARGV[3], '');
  metadata_columns TEXT[] := string_to_array(COALESCE(TG_ARGV[4], ''), ',');
  record_column TEXT;
  metadata_column TEXT;
  record_parts TEXT[] := ARRAY[]::TEXT[];
  record_value TEXT;
  user_id INTEGER := NULL;
  event_operation TEXT;
  metadata JSONB := '{}'::JSONB;
BEGIN
  row_data := CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
  old_data := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) ELSE '{}'::JSONB END;

  IF TG_OP = 'UPDATE' AND to_jsonb(OLD) = to_jsonb(NEW) THEN
    RETURN NEW;
  END IF;

  FOREACH record_column IN ARRAY record_columns LOOP
    record_value := row_data ->> btrim(record_column);
    IF record_value IS NULL THEN
      IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
      RETURN NEW;
    END IF;
    record_parts := array_append(record_parts, record_value);
  END LOOP;

  IF user_column <> '' THEN
    user_id := NULLIF(row_data ->> user_column, '')::INTEGER;
  END IF;

  event_operation := lower(TG_OP);
  IF TG_OP = 'DELETE' OR (
    soft_delete_column <> ''
    AND COALESCE((row_data ->> soft_delete_column)::BOOLEAN, FALSE)
    AND NOT COALESCE((old_data ->> soft_delete_column)::BOOLEAN, FALSE)
  ) THEN
    event_operation := 'delete';
  END IF;

  FOREACH metadata_column IN ARRAY metadata_columns LOOP
    metadata_column := btrim(metadata_column);
    IF metadata_column <> '' THEN
      metadata := metadata || jsonb_build_object(
        metadata_column,
        row_data -> metadata_column
      );
    END IF;
  END LOOP;

  INSERT INTO mobile_sync_changes (
    entity,
    record_id,
    id_utilizador,
    operation,
    metadata_json
  ) VALUES (
    entity_name,
    array_to_string(record_parts, ':'),
    user_id,
    event_operation,
    NULLIF(metadata, '{}'::JSONB)
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Não foi possível registar alteração mobile em %.%', TG_TABLE_NAME, TG_OP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION mobile_sync_log_submission_related()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  old_data JSONB;
  entity_name TEXT := TG_ARGV[0];
  record_columns TEXT[] := string_to_array(TG_ARGV[1], ',');
  soft_delete_column TEXT := COALESCE(TG_ARGV[2], '');
  metadata_columns TEXT[] := string_to_array(COALESCE(TG_ARGV[3], ''), ',');
  column_name TEXT;
  record_parts TEXT[] := ARRAY[]::TEXT[];
  metadata JSONB := '{}'::JSONB;
  user_id INTEGER;
  event_operation TEXT;
