BEGIN;

ALTER TABLE notificacoes
  ADD COLUMN IF NOT EXISTS updated_notificacao TIMESTAMP WITH TIME ZONE;

UPDATE notificacoes
SET updated_notificacao = data_envio
WHERE updated_notificacao IS NULL;

ALTER TABLE notificacoes
  ALTER COLUMN updated_notificacao SET DEFAULT CURRENT_TIMESTAMP,
  ALTER COLUMN updated_notificacao SET NOT NULL;

ALTER TABLE permissoes
  ADD COLUMN IF NOT EXISTS updated_permissao TIMESTAMP WITH TIME ZONE;

UPDATE permissoes
SET updated_permissao = CURRENT_TIMESTAMP
WHERE updated_permissao IS NULL;

ALTER TABLE permissoes
  ALTER COLUMN updated_permissao SET DEFAULT CURRENT_TIMESTAMP,
  ALTER COLUMN updated_permissao SET NOT NULL;

ALTER TABLE requisitos_badge
  ADD COLUMN IF NOT EXISTS updated_requisito_badge TIMESTAMP WITH TIME ZONE;

UPDATE requisitos_badge AS relacao
SET updated_requisito_badge = COALESCE(badge.update_badge, CURRENT_TIMESTAMP)
FROM badges AS badge
WHERE badge.id_badge = relacao.id_badge
  AND relacao.updated_requisito_badge IS NULL;

UPDATE requisitos_badge
SET updated_requisito_badge = CURRENT_TIMESTAMP
WHERE updated_requisito_badge IS NULL;

ALTER TABLE requisitos_badge
  ALTER COLUMN updated_requisito_badge SET DEFAULT CURRENT_TIMESTAMP,
  ALTER COLUMN updated_requisito_badge SET NOT NULL;

ALTER TABLE objetivos
  ADD COLUMN IF NOT EXISTS data_eliminacao TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS sync_requisitos_badges_deleted (
  id_sync_delete INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_badge INTEGER NOT NULL,
  id_requisito INTEGER NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS sync_recetores_deleted (
  id_sync_delete INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_notificacao INTEGER NOT NULL,
  id_utilizador INTEGER NOT NULL,
  deleted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_notificacoes_updated_notificacao
  ON notificacoes (updated_notificacao);

CREATE INDEX IF NOT EXISTS idx_permissoes_updated_permissao
  ON permissoes (updated_permissao);

CREATE INDEX IF NOT EXISTS idx_requisitos_badge_updated
  ON requisitos_badge (updated_requisito_badge);

CREATE INDEX IF NOT EXISTS idx_objetivos_data_eliminacao
  ON objetivos (data_eliminacao);

CREATE INDEX IF NOT EXISTS idx_sync_requisitos_badges_deleted_at
  ON sync_requisitos_badges_deleted (deleted_at);

CREATE INDEX IF NOT EXISTS idx_sync_requisitos_badges_deleted_ids
  ON sync_requisitos_badges_deleted (id_badge, id_requisito);

CREATE INDEX IF NOT EXISTS idx_sync_recetores_deleted_at
  ON sync_recetores_deleted (deleted_at);

CREATE INDEX IF NOT EXISTS idx_sync_recetores_deleted_ids
  ON sync_recetores_deleted (id_notificacao, id_utilizador);

COMMIT;
