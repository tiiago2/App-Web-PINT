BEGIN;

CREATE TABLE IF NOT EXISTS mobile_devices (
  id_mobile_device INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_utilizador INTEGER NOT NULL,
  device_id TEXT NOT NULL,
  fcm_token TEXT NOT NULL,
  platform TEXT NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_mobile_devices_user'
      AND conrelid = 'mobile_devices'::regclass
  ) THEN
    ALTER TABLE mobile_devices
      ADD CONSTRAINT fk_mobile_devices_user
      FOREIGN KEY (id_utilizador)
      REFERENCES utilizador (id_utilizador)
      ON DELETE CASCADE;
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'uq_mobile_devices_user_device'
      AND conrelid = 'mobile_devices'::regclass
  ) THEN
    ALTER TABLE mobile_devices
      ADD CONSTRAINT uq_mobile_devices_user_device
      UNIQUE (id_utilizador, device_id);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_mobile_devices_user_active
  ON mobile_devices (id_utilizador, ativo);

CREATE INDEX IF NOT EXISTS idx_mobile_devices_fcm_token
  ON mobile_devices (fcm_token);

CREATE INDEX IF NOT EXISTS idx_mobile_devices_device_id
  ON mobile_devices (device_id);

COMMIT;
