    RETURN NEW;
  END IF;

  SELECT id_utilizador
  INTO user_id
  FROM submissoes
  WHERE id_submissao = (row_data ->> 'id_submissao')::INTEGER;

  IF user_id IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
