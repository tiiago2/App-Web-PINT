BEGIN;

CREATE TABLE IF NOT EXISTS mobile_refresh_tokens (
  id_mobile_refresh_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_utilizador INTEGER NOT NULL,
  device_id VARCHAR(255) NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  revoked_at TIMESTAMP WITH TIME ZONE NULL,
  replaced_by_token_id INTEGER NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_mobile_refresh_tokens_user'
      AND conrelid = 'mobile_refresh_tokens'::regclass
  ) THEN
    ALTER TABLE mobile_refresh_tokens
      ADD CONSTRAINT fk_mobile_refresh_tokens_user
      FOREIGN KEY (id_utilizador)
      REFERENCES utilizador (id_utilizador)
      ON DELETE CASCADE;
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_mobile_refresh_tokens_replacement'
      AND conrelid = 'mobile_refresh_tokens'::regclass
  ) THEN
    ALTER TABLE mobile_refresh_tokens
      ADD CONSTRAINT fk_mobile_refresh_tokens_replacement
      FOREIGN KEY (replaced_by_token_id)
      REFERENCES mobile_refresh_tokens (id_mobile_refresh_token)
      ON DELETE SET NULL;
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_mobile_refresh_tokens_token_hash
  ON mobile_refresh_tokens (token_hash);

CREATE INDEX IF NOT EXISTS idx_mobile_refresh_tokens_user_device
  ON mobile_refresh_tokens (id_utilizador, device_id, revoked_at);

CREATE INDEX IF NOT EXISTS idx_mobile_refresh_tokens_expires_at
  ON mobile_refresh_tokens (expires_at);

CREATE INDEX IF NOT EXISTS idx_mobile_refresh_tokens_replaced_by
  ON mobile_refresh_tokens (replaced_by_token_id);

COMMIT;
