  IF TG_OP = 'DELETE' OR (
    soft_delete_column <> ''
    AND COALESCE((row_data ->> soft_delete_column)::BOOLEAN, FALSE)
    AND NOT COALESCE((old_data ->> soft_delete_column)::BOOLEAN, FALSE)
  ) THEN
    event_operation := 'delete';
  END IF;

  FOREACH column_name IN ARRAY metadata_columns LOOP
    column_name := btrim(column_name);
    IF column_name <> '' THEN
      metadata := metadata || jsonb_build_object(column_name, row_data -> column_name);
    END IF;
  END LOOP;

  INSERT INTO mobile_sync_changes (
    entity, record_id, id_utilizador, operation, metadata_json
  ) VALUES (
    entity_name,
    array_to_string(record_parts, ':'),
    user_id,
    event_operation,
    NULLIF(metadata, '{}'::JSONB)
  );

